import assert from "node:assert/strict";
import fs from "node:fs";
const root=new URL("../",import.meta.url).pathname;
const report=JSON.parse(fs.readFileSync(root+"reports/current/scoring-audit.v2.3.json","utf8"));
assert.equal(report.version,"2.3");
const trait=report.matcher.trait_target;
assert.equal(trait.profiles,17);
assert.equal(trait.top1_agreement,14);
assert.ok(trait.top1_rate>=0 && trait.top1_rate<=1);
assert.ok(trait.recall_at_3_rate>=trait.top1_rate);
const all=report.matcher.all_curated_edges_context_only;
assert.equal(all.profiles,25);
assert.ok(all.top1_rate<=trait.top1_rate,"mixed relation modes must not be presented as better target accuracy");
assert.equal(report.distributions.data_confidence.n,25);
assert.ok(report.distributions.relation_score.n>=25);
assert.ok(Array.isArray(report.warnings));
assert.match(report.note,/not probabilities/i);
const native=new Set(report.native_rid_guardrail.map(x=>x.prophet_id));
for(const id of ["isa","muhammad"]) assert.ok(native.has(id),`expected native RID guardrail for ${id}`);
console.log(`Scoring audit: trait top1 ${(100*trait.top1_rate).toFixed(1)}%, trait recall@3 ${(100*trait.recall_at_3_rate).toFixed(1)}%; all-edge diagnostic ${(100*all.top1_rate).toFixed(1)}%`);
